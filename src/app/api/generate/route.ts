import { NextRequest, NextResponse } from "next/server";
import Groq from "groq-sdk";

const groq = new Groq({
  apiKey: process.env.GROQ_API_KEY,
});

export async function POST(request: NextRequest) {
  try {
    const { topic, grade, length, gender, type } = await request.json();

    if (!topic?.trim()) {
      return NextResponse.json(
        { error: "لطفاً موضوع انشا را وارد کنید." },
        { status: 400 }
      );
    }

    const prompt = `
یک انشای فارسی برای یک دانش‌آموز ایرانی بنویس.

موضوع: ${topic}
پایه تحصیلی: ${grade}
طول انشا: ${length}
جنسیت دانش‌آموز: ${gender}
نوع انشا: ${type}

قوانین بسیار مهم:

1. متن باید شبیه انشایی باشد که یک دانش‌آموز واقعی در دفتر مدرسه خودش نوشته است.

2. اولویت اصلی، طبیعی بودن متن است؛ نه استفاده از کلمات زیبا و ادبی.

3. سطح کلمات، جمله‌ها و طرز فکر باید کاملاً متناسب با ${grade} باشد.

4. جمله‌ها را بیش از حد کامل، مرتب و پیچیده ننویس.

5. از کلمات سخت، دانشگاهی، رسمی و ادبی که برای یک دانش‌آموز ${grade} غیرطبیعی هستند استفاده نکن.

6. از جمله‌های کلیشه‌ای و رایج متن‌های تولیدشده توسط هوش مصنوعی استفاده نکن، مانند:
«یکی از مهم‌ترین نعمت‌های خداوند...»
«از دیرباز تاکنون...»
«در دنیای امروز...»
«همه ما می‌دانیم که...»
«موضوع مورد بحث ما...»
و عبارت‌های مشابه.

7. مقدمه را مستقیماً و طبیعی شروع کن. لازم نیست همیشه با یک جمله کلی درباره اهمیت موضوع شروع شود.

8. جمله‌ها باید طول‌های متفاوتی داشته باشند. همه جمله‌ها را با یک الگوی ثابت ننویس.

9. پاراگراف‌ها نباید شبیه یک قالب تکراری باشند.

10. از تکرار بی‌دلیل کلمات و ایده‌ها خودداری کن.

11. اگر موضوع خاطره یا تجربه شخصی است، چند جزئیات ساده و قابل‌باور اضافه کن.

12. احساسات را ساده و طبیعی بیان کن. از توصیف‌های بیش از حد شاعرانه استفاده نکن.

13. اگر موضوع داستانی است، داستان باید ساده و قابل‌باور باشد و اتفاقات آن برای یک دانش‌آموز مناسب باشد.

14. اگر موضوع نظر شخصی است، نظر را با زبان ساده و دانش‌آموزی بیان کن.

15. جنسیت انتخاب‌شده را فقط در جاهایی که طبیعی است در سبک و جزئیات متن لحاظ کن. نباید مصنوعی یا اغراق‌آمیز باشد.

16. از اصطلاحات و اطلاعاتی که یک دانش‌آموز در این پایه معمولاً استفاده نمی‌کند دوری کن.

17. متن نباید شبیه مقاله، کتاب یا متن آموزشی باشد.

18. انشا باید شروع، ادامه و پایان طبیعی داشته باشد، اما از ساختارهای خشک و قابل‌تشخیص استفاده نکن.

19. متن باید منسجم باشد و از موضوع اصلی خارج نشود.

20. طول متن باید با گزینه «${length}» هماهنگ باشد.

21. متن کاملاً فارسی باشد.

22. هیچ توضیحی درباره نحوه نوشتن، هوش مصنوعی یا قوانین بالا نده.

23. هیچ عنوانی مثل «مقدمه»، «بدنه» یا «نتیجه‌گیری» ننویس.

24. فقط متن نهایی انشا را خروجی بده.

مهم:
اگر بین «زیباتر نوشتن» و «طبیعی‌تر نوشتن» مجبور به انتخاب شدی، همیشه طبیعی‌تر نوشتن را انتخاب کن.
`;

    const completion = await groq.chat.completions.create({
      model: "openai/gpt-oss-120b",
      messages: [
        {
          role: "system",
          content: `
تو یک نویسنده انشا برای دانش‌آموزان ایرانی هستی.

مهم‌ترین هدف تو تولید متنی طبیعی و متناسب با سن دانش‌آموز است.
متن نباید شبیه متن رسمی، مقاله، کتاب یا نوشته تولیدشده توسط یک سیستم باشد.

مثل یک دانش‌آموز واقعی فکر کن و با سطح زبانی همان دانش‌آموز بنویس.
          `.trim(),
        },
        {
          role: "user",
          content: prompt,
        },
      ],
      temperature: 0.8,
    });

    const result =
      completion.choices[0]?.message?.content?.trim() || "";

    return NextResponse.json({
      result,
    });
  } catch (error) {
    console.error("Generate essay error:", error);

    return NextResponse.json(
      {
        error:
          "در ساخت انشا مشکلی پیش آمد. لطفاً دوباره تلاش کنید.",
      },
      { status: 500 }
    );
  }
}